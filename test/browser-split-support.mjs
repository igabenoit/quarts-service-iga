import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {liveAppFixture} from './live-app-fixture.mjs';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const f=await liveAppFixture();let browser;
try{
  const cookie=(await f.call('POST','/api/login',{body:{code:'audit-admin-test'}})).cookie;
  const {departments}=(await f.call('GET','/api/departments/meta',{cookie})).body;
  const dep=departments.find(d=>d.key==='epicerie'),week='2026-11-23';
  await f.call('POST','/api/departments/people',{cookie,body:{name:'Journée Test',group:'regular',active:true,departments:[dep.id],availability:{}}});
  browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE});
  const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.context().addCookies([{name:cookie.split('=')[0],value:cookie.slice(cookie.indexOf('=')+1),url:f.base}]);
  const url=f.base+`/departements?department=${dep.id}&week=${week}`;
  await page.goto(url);
  await page.getByRole('button',{name:/Journée Test, Lundi,/}).click();
  await page.locator('#cellStart').fill('08:00');await page.locator('#cellEnd').fill('12:00');
  await page.locator('#addServicePortion').check();await page.locator('#portionAssignment').selectOption('delivery');
  await page.locator('#portionStart').fill('11:00');await page.locator('#portionEnd').fill('17:00');
  await page.getByRole('button',{name:'Enregistrer cette journée',exact:true}).click();
  assert.match(await page.locator('#cellError').textContent(),/chevaucher/);
  await page.locator('#portionStart').fill('13:00');
  assert.match(await page.locator('#resolvedShift').textContent(),/Total journée : 8 h/);
  await page.getByRole('button',{name:'Enregistrer cette journée',exact:true}).click();
  const totals=await page.locator('.department-hours').textContent();
  assert.match(totals,/Régulier : 4 h/);assert.match(totals,/Livraison : 4 h/);assert.match(totals,/Grand total : 8 h/);
  const saving=page.waitForResponse(r=>r.request().method()==='PUT'&&r.url().includes('/weeks/'));
  await page.locator('#saveDraft').click();assert.equal((await saving).status(),200);
  await page.reload();await page.getByRole('button',{name:/Journée Test, Lundi,/}).click();
  assert.equal(await page.locator('#addServicePortion').isChecked(),true);assert.equal(await page.locator('#portionStart').inputValue(),'13:00');
  await page.locator('#cellDialog button[data-close]').click();
  assert.match(await page.locator('#scheduleGrid').textContent(),/08:00–12:00/);assert.match(await page.locator('#scheduleGrid').textContent(),/13:00–17:00/);
  await page.locator('[data-view="print"]').click();await page.locator('#printKind').selectOption('filled');
  assert.match(await page.locator('#printPreview').textContent(),/Quart complet · 8 h/);
  await page.locator('#printSheet').click();await page.locator('#downloadPdf').waitFor({state:'visible'});
  assert.match(await page.locator('#pdfStatus').innerText(),/1 page\(s\) légale/);
  await page.goto(f.base+'/');await page.locator('#weekPicker').fill(week);await page.locator('#weekPicker').dispatchEvent('change');
  await page.waitForFunction(()=>document.querySelector('#scheduleBoard')?.textContent.includes('Journée Test'));
  assert.match(await page.locator('#scheduleBoard').textContent(),/Livraison : 4 h/);
  const support=(await f.call('GET',`/api/weeks/${week}`,{cookie})).body.departmentSupport;
  assert.equal(support.length,1);assert.equal(support[0].startMinute,780);assert.equal(support[0].paidMinutes,240);
  await page.goto(url);await page.getByRole('button',{name:/Journée Test, Lundi,/}).click();await page.locator('#addServicePortion').uncheck();
  await page.getByRole('button',{name:'Enregistrer cette journée',exact:true}).click();
  assert.match(await page.locator('.department-hours').textContent(),/Grand total : 4 h/);assert.doesNotMatch(await page.locator('.department-hours').textContent(),/Livraison/);
  assert.deepEqual(errors,[]);console.log('Split day verified in browser: overlap rejection, 4 h department + 4 h delivery, save/reopen, PDF, Service projection, removal.');
}finally{await browser?.close();await f.close();}
