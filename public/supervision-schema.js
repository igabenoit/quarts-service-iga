export const ratings = ['Respecté', 'Non respecté', 'Sans objet'];
export const items = sections.flatMap(section => section.rows);

export function normalizeSupervision(value) {
  function invalid() {
    throw Object.assign(new Error('Les réponses de la grille de supervision sont invalides.'), {status: 400});
  }
  function field(name, limit) {
    const text = value[name];
    if (typeof text !== 'string' || text.length > limit) invalid();
    return text.trim();
  }
  function flags(list, count) {
    if (!Array.isArray(list) || list.length !== count || list.some(flag => typeof flag !== 'boolean')) invalid();
    return list;
  }
  if (!value || value.version !== 1 || !Array.isArray(value.rows) || value.rows.length !== items.length) invalid();
  return {
    version: 1,
    company: field('company', 160),
    store: field('store', 80),
    other: field('other', 2000),
    actions: flags(value.actions, actions.length),
    rows: items.map((item, index) => {
      const row = value.rows[index];
      if (!row || !['', ...ratings].includes(row.rating)) invalid();
      return {rating: row.rating, tasks: flags(row.tasks, item.tasks.length)};
    })
  };
}
